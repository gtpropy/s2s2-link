#!/usr/bin/env python3
"""Generates Mission/seal_tables.S: lookup tables for seal_core.S (read-only data)."""
import sys
from fec_model import EXP, LOG, GEN

def bytes_lines(vals, per=16):
    out = []
    for i in range(0, len(vals), per):
        out.append("    .byte " + ", ".join("0x%02X" % v for v in vals[i:i + per]))
    return "\n".join(out)

def half_lines(vals, per=8):
    out = []
    for i in range(0, len(vals), per):
        out.append("    .hword " + ", ".join("0x%03X" % v for v in vals[i:i + per]))
    return "\n".join(out)

# exp: 0..509 periodic, 510..511 pad, 512..543 zero zone (log(0) maps here)
exp_tab = [EXP[i] for i in range(510)] + [0, 0] + [0] * 32
assert len(exp_tab) == 544
# log: halfwords, log(0) = 512 -> reads the zero zone
log_tab = [512] + [LOG[v] for v in range(1, 256)]
# gl[i] = log of generator coefficient x^(31-i)
gl_tab = [LOG[GEN[i + 1]] for i in range(32)]

src = """@ GENERATED by fec_asm_tests/gen_seal_tables.py -- do not edit.
@ Lookup tables for seal_core.S (byte math, poly 0x11D).
    .syntax unified
    .cpu cortex-m0plus
    .thumb

    .section .rodata.seal,"a",%%progbits
    .align 2
    .global seal_exp
seal_exp:                       @ 544 B: exp[0..509], pad, 32 zero bytes
%s

    .align 2
    .global seal_log
seal_log:                       @ 256 halfwords: log[0]=512 (zero zone)
%s

    .align 2
    .global seal_gl
seal_gl:                        @ 32 B: log of generator coeffs
%s
""" % (bytes_lines(exp_tab), half_lines(log_tab), bytes_lines(gl_tab))

out = sys.argv[1] if len(sys.argv) > 1 else "seal_tables.S"
open(out, "w").write(src)
print("wrote", out, "exp", len(exp_tab), "log", len(log_tab), "gl", len(gl_tab))
