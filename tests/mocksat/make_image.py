#!/usr/bin/env python3
"""Generate mock_image.h: the small test picture the mock satellite downlinks (a "quick exam" of the image path).
Run with tools/.venv/bin/python tests/mocksat/make_image.py   (needs Pillow). The result is checked in; rerun only to change the picture."""
import io, os, sys
from PIL import Image, ImageDraw

W, H = 96, 64
im = Image.new("RGB", (W, H))
px = im.load()
for y in range(H):                       # night sky to Earth limb
    for x in range(W):
        if y < 40:
            px[x, y] = (6, 10 + y // 3, 40 + y)
        else:
            k = (y - 40) / 24.0
            px[x, y] = (int(20 + 30 * k), int(70 + 80 * k), int(150 - 40 * k))
d = ImageDraw.Draw(im)
for sx, sy in ((8, 6), (30, 12), (52, 5), (71, 14), (86, 8), (18, 26), (63, 28), (90, 31)):
    d.point((sx, sy), fill=(255, 255, 255))
d.rectangle((38, 18, 58, 30), fill=(230, 230, 235), outline=(255, 255, 255))      # the "satellite"
d.rectangle((24, 22, 36, 26), fill=(30, 60, 200)); d.rectangle((60, 22, 72, 26), fill=(30, 60, 200))
d.text((14, 48), "S2S2 MOCK", fill=(255, 255, 255))
buf = io.BytesIO()
im.save(buf, "JPEG", quality=35, subsampling=2, optimize=True)
data = buf.getvalue()
assert data[:2] == b"\xff\xd8" and data[-2:] == b"\xff\xd9"

here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, "mock_image.h"), "w") as f:
    f.write("/* GENERATED by make_image.py: the JPEG the mock satellite downlinks (%dx%d, %d bytes). */\n" % (W, H, len(data)))
    f.write("#ifndef MOCK_IMAGE_H\n#define MOCK_IMAGE_H\n#include <stdint.h>\n#define MOCK_IMAGE_SIZE %du\n" % len(data))
    f.write("static const uint8_t g_mock_image[MOCK_IMAGE_SIZE] = {\n")
    for i in range(0, len(data), 16):
        f.write("    " + ", ".join("0x%02X" % b for b in data[i:i + 16]) + ",\n")
    f.write("};\n#endif\n")
im.save(os.path.join(here, "mock_image_preview.jpg"))
print("image bytes", len(data), "fragments", -(-len(data) // 128))
